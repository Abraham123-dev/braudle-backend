import { asyncHandler } from '../utils/asyncHandler.js';
import { AppError } from '../utils/AppError.js';
import Quiz from '../models/Quiz.model.js';
import Session from '../models/Session.model.js';
import Document from '../models/Document.model.js';
import * as QuizService from '../services/quiz.service.js';
import * as HuggingFaceService from '../services/huggingface.service.js';
import * as ProfileService from '../services/profile.service.js';
import { calculateScore } from '../utils/scoreCalculator.js';

const stripAnswers = (questions) => questions.map((q) => ({
  _id: q._id,
  question: q.question,
  type: q.type,
  options: q.options,
}));

/**
 * Generate a new quiz for a session
 */
export const generateQuiz = asyncHandler(async (req, res) => {
  const { sessionId } = req.body;
  const userId = req.user.id;

  // Verify session belongs to user
  const session = await Session.findOne({ _id: sessionId, userId });
  if (!session) throw new AppError('Session not found or access denied', 404);

  // Fetch document topics for adaptive learning traceability
  const document = await Document.findById(session.documentId).select('topics');

  // Cache-aware profile fetch
  const profile = await ProfileService.getProfile(userId);
  if (!profile) throw new AppError('Student profile not found', 404);

  // Check if a quiz already exists for this session
  // Depending on requirements, we might allow multiple, but let's assume 1 per session
  let existingQuiz = await Quiz.findOne({ sessionId });
  if (existingQuiz && existingQuiz.score === undefined) {
    // If a quiz exists and hasn't been submitted, return it with stripped answers
    return res.status(200).json({ 
      status: 'success', 
      quiz: { ...existingQuiz.toObject(), questions: stripAnswers(existingQuiz.questions) } 
    });
  }

  // Call the AI service to generate a new quiz
  const quizData = await QuizService.generateQuiz(
    session.documentId, 
    profile, 
    5, 
    document?.topics || []
  );

  const questions = quizData.questions || quizData; // Handle if AI returns array or object

  if (!Array.isArray(questions) || questions.length === 0) {
    throw new AppError('Invalid quiz generated by AI', 500);
  }

  // Create Quiz record
  const quiz = await Quiz.create({
    sessionId: session._id,
    documentId: session.documentId,
    questions: questions,
    totalQuestions: questions.length,
  });

  // Strip answers from response so students can't inspect element to cheat
  const cleanQuestions = stripAnswers(quiz.questions);

  res.status(201).json({
    status: 'success',
    quiz: {
      ...quiz.toObject(),
      questions: cleanQuestions,
    },
  });
});

/**
 * Generate a custom practice assessment (exam/quiz)
 */
export const generateCustomAssessment = asyncHandler(async (req, res) => {
  const { documentId, format, difficulty, numQuestions } = req.body;
  const userId = req.user.id;

  const document = await Document.findOne({ _id: documentId, userId });
  if (!document) throw new AppError('Document not found or access denied', 404);

  // We need to anchor this to a session for history and grading.
  // Create a fast, background 'exam' session.
  const session = await Session.create({
    userId,
    documentId,
    mode: format === 'theory' || difficulty === 'expert' ? 'exam' : 'quiz',
    status: 'active'
  });

  const quizData = await QuizService.generateCustomAssessment(documentId, { 
    format, 
    difficulty, 
    numQuestions,
    documentTopics: document.topics || []
  });
  const questions = quizData.questions || quizData;

  if (!Array.isArray(questions) || questions.length === 0) {
    throw new AppError('Invalid assessment generated by AI', 500);
  }

  const quiz = await Quiz.create({
    sessionId: session._id,
    documentId,
    questions: questions,
    totalQuestions: questions.length,
  });

  res.status(201).json({
    status: 'success',
    quiz: {
      ...quiz.toObject(),
      questions: stripAnswers(quiz.questions),
    },
  });
});

/**
 * Submit answers and grade the quiz using zero-cost embeddings
 */
export const submitQuiz = asyncHandler(async (req, res) => {
  const { quizId } = req.params;
  const { answers } = req.body; // Array of { questionId, answer }
  const userId = req.user.id;

  // Fetch the quiz and populate session to verify ownership
  const quiz = await Quiz.findById(quizId).populate('sessionId');
  if (!quiz) throw new AppError('Quiz not found', 404);
  if (quiz.sessionId.userId.toString() !== userId) {
    throw new AppError('Forbidden: Access denied', 403);
  }
  if (quiz.score !== undefined) {
    throw new AppError('Quiz has already been submitted', 400);
  }

  // Grade each answer
  for (let q of quiz.questions) {
    const studentSubmission = answers.find(a => a.questionId.toString() === q._id.toString());
    
    if (studentSubmission) {
      q.studentAnswer = studentSubmission.answer;

      if (q.type === 'mcq' || q.type === 'true_false') {
        // String matching or zero-cost semantic similarity
        // Since MCQs can have slight variations, we'll use HF embeddings
        const similarity = await HuggingFaceService.checkAnswerSimilarity(
          q.studentAnswer,
          q.answer
        );
        q.isCorrect = similarity === 'correct';
      } else {
        // Theory short answer -> Semantic similarity via HF embeddings
        const similarity = await HuggingFaceService.checkAnswerSimilarity(
          q.studentAnswer,
          q.answer
        );
        // We consider partial as correct enough or mark strictly. Let's mark correct if 'correct' or 'partial' for now, 
        // or just 'correct' depending on strictness. The guidelines say similarity checks handle this.
        q.isCorrect = similarity === 'correct' || similarity === 'partial'; 
      }
    } else {
      q.studentAnswer = '';
      q.isCorrect = false;
    }
  }

  // Calculate score
  const score = calculateScore(quiz.questions);
  quiz.score = score;
  quiz.submittedAt = new Date();

  await quiz.save();

  // Handle potential level upgrade and XP
  const newLevel = await ProfileService.updateProfileAfterQuiz(userId, score, quiz.questions);

  res.status(200).json({
    status: 'success',
    score: quiz.score,
    quiz,
    newLevel
  });
});

/**
 * Get the user's quiz history
 */
export const getQuizHistory = asyncHandler(async (req, res) => {
  const userId = req.user.id;

  // Find all sessions for user
  const sessions = await Session.find({ userId }).select('_id');
  const sessionIds = sessions.map(s => s._id);

  // Find quizzes matching those sessions
  const quizzes = await Quiz.find({ sessionId: { $in: sessionIds } })
    .populate('documentId', 'title subject')
    .sort({ createdAt: -1 });

  res.status(200).json({
    status: 'success',
    results: quizzes.length,
    quizzes
  });
});

/**
 * Get a specific quiz detail
 */
export const getQuiz = asyncHandler(async (req, res) => {
  const { quizId } = req.params;
  const userId = req.user.id;

  const quiz = await Quiz.findById(quizId).populate('sessionId');
  if (!quiz) throw new AppError('Quiz not found', 404);
  
  if (quiz.sessionId.userId.toString() !== userId) {
    throw new AppError('Forbidden: Access denied', 403);
  }

  let returnedQuiz = quiz.toObject();
  if (returnedQuiz.score === undefined) {
    returnedQuiz.questions = stripAnswers(returnedQuiz.questions);
  }

  res.status(200).json({ status: 'success', quiz: returnedQuiz });
});

// ── Flashcard parser ─────────────────────────────────────────────────────────
/**
 * Parses FLASHCARD pipe-delimited markers out of an AI response.
 * Format generated by AI: FLASHCARD | TOPIC: x | FRONT: y | BACK: z
 *
 * @param {string} text - Raw AI response text
 * @returns {Array<{topic, front, back}>} Parsed flashcard objects
 */
const parseFlashcardsFromResponse = (text) => {
  if (!text) return [];
  const flashcards = [];
  const lines = text.split('\n');

  for (const line of lines) {
    if (!line.startsWith('FLASHCARD |')) continue;

    const topicMatch  = line.match(/TOPIC:\s*([^|]+)/i);
    const frontMatch  = line.match(/FRONT:\s*([^|]+)/i);
    const backMatch   = line.match(/BACK:\s*(.+)$/i);

    if (topicMatch && frontMatch && backMatch) {
      flashcards.push({
        topic: topicMatch[1].trim(),
        front: frontMatch[1].trim(),
        back:  backMatch[1].trim(),
      });
    }
  }

  return flashcards;
};

// ── YouTube marker processor ──────────────────────────────────────────────────
/**
 * Detects a [YOUTUBE_SEARCH: "query"] marker in the AI response,
 * fetches a real video, and replaces the marker with a formatted link.
 * Non-blocking — if YouTube API fails, marker is simply removed.
 *
 * @param {string} text - AI response text possibly containing the marker
 * @returns {Promise<string>} Enriched text with real YouTube link (or marker removed)
 */
const resolveYouTubeMarker = async (text) => {
  const markerRegex = /\[YOUTUBE_SEARCH:\s*"([^"]+)"\]/i;
  const match = text.match(markerRegex);

  if (!match) return text;

  const query = match[1];
  const videos = await YouTubeService.searchYouTube(query, 1);

  if (videos.length > 0) {
    const videoText = YouTubeService.formatVideoSuggestion(videos[0]);
    return text.replace(markerRegex, videoText);
  }

  // No results or API unavailable: remove marker cleanly
  return text.replace(markerRegex, '');
};

/**
 * Starts a new learning session for a specific document
 */
export const startSession = asyncHandler(async (req, res) => {
  const { documentId, mode } = req.body;
  const userId = req.user.id;

  // 1. Verify document exists, belongs to user, and is processed
  const document = await Document.findOne({ _id: documentId, userId });
  if (!document) throw new AppError('Document not found', 404);
  if (document.userId.toString() !== userId) throw new AppError('Forbidden: Access denied', 403);
  if (document.processingStatus !== 'ready') {
    throw new AppError('Document is still being processed. Please wait.', 400);
  }

  // 2. Mark any other active sessions for this document as 'abandoned'
  await Session.updateMany(
    { userId, documentId, status: 'active' },
    { status: 'abandoned' }
  );

  // 3. Create the session
  const session = await Session.create({
    userId,
    documentId,
    mode: mode || 'understand',
    currentChunkIndex: 0,
  });

  // 4. Initialize empty conversation
  await Conversation.create({
    sessionId: session._id,
    userId,
    messages: [],
  });

  res.status(201).json({
    status: 'success',
    sessionId: session._id,
    mode: session.mode,
    message: "Your study session is ready! Let's start learning together.",
  });
});

/**
 * Handles real-time AI teaching via Server-Sent Events (SSE).
 * Enriches prompts with full document context and resolves YouTube markers post-stream.
 */
export const chatSession = asyncHandler(async (req, res) => {
  const { id: sessionId } = req.params;
  const { message } = req.body;
  const userId = req.user.id;

  // Concurrent Stream Protection
  const streamLockKey = CACHE_KEYS.ACTIVE_STREAM(userId);
  const activeStream = await getCached(streamLockKey);
  if (activeStream) throw new AppError('Only one active tutoring stream allowed at a time', 429);

  // 1. Get Session and associated data
  const session = await Session.findOne({ _id: sessionId, userId });
  if (!session || (session.status !== 'active' && session.status !== 'completed')) {
    throw new AppError('Forbidden: Access denied or session inactive', 403);
  }

  // Auto-reactivate completed sessions when new messages arrive
  if (session.status === 'completed') {
    await Session.updateMany(
      { userId, documentId: session.documentId, status: 'active', _id: { $ne: session._id } },
      { status: 'abandoned' }
    );
    session.status = 'active';
    session.completedAt = undefined;
    await session.save();
  }

  // Fetch document with all context fields needed for the prompt
  const document = await Document.findById(session.documentId)
    .select('chunks topics summary title totalChunks');
  if (!document) throw new AppError('Document not found', 404);

  // Cache-aware profile fetch — avoids a MongoDB hit on every chat message
  const profile = await ProfileService.getProfile(userId);
  if (!profile) throw new AppError('Student profile not found', 404);

  // Conversation Null Safety
  let conversation = await Conversation.findOne({ sessionId });
  if (!conversation) {
    conversation = await Conversation.create({ sessionId, userId, messages: [] });
  }

  // 2. Build full document context for the prompt
  const documentContext = {
    title:              document.title || 'this document',
    topics:             document.topics || [],
    currentChunkIndex:  session.currentChunkIndex,
    totalChunks:        document.totalChunks || document.chunks?.length || 1,
    preparationStyle:   session.preparationStyle || 'mixed',
  };

  const currentChunk = (document.chunks && document.chunks[session.currentChunkIndex]) || '';
  const history = (conversation.messages || []).slice(-10); // Last 5 exchanges

  // Expensive AI Cache Check — only cache initial "ready" responses, not follow-ups
  const cacheKey = CACHE_KEYS.TEACH(document._id, session.currentChunkIndex, profile.level);
  const cachedResponse = await getCached(cacheKey);

  // 4. Setup SSE Headers
  res.setHeader('Content-Type', 'text/event-stream');
  res.setHeader('Cache-Control', 'no-cache');
  res.setHeader('Connection', 'keep-alive');

  // Lock the stream
  await setCached(streamLockKey, sessionId, CACHE_TTL.STREAM);

  // 3. Build contextual prompt
  const systemPrompt = buildTeachPrompt(currentChunk, profile, session.mode, documentContext);

  let fullAIResponse = '';
  let isClosed = false;
  let stream;

  req.on('close', () => {
    isClosed = true;
    deleteCached(streamLockKey);
    if (stream?.abort) stream.abort();
  });

  try {
    if (cachedResponse && message === 'ready') {
      fullAIResponse = cachedResponse;
      res.write(`data: ${JSON.stringify({ token: cachedResponse })}\n\n`);
    } else {
      stream = await AIService.streamGroq(systemPrompt, message, history);

      for await (const part of stream) {
        if (isClosed) break;
        const chunkValue = part.choices[0]?.delta?.content || '';
        if (chunkValue) {
          fullAIResponse += chunkValue;
          res.write(`data: ${JSON.stringify({ token: chunkValue })}\n\n`);
        }
      }
    }

    // ── Post-stream processing ────────────────────────────────────────────
    // 1. Resolve YouTube search marker (if any) — replace with real link
    const enrichedResponse = await resolveYouTubeMarker(fullAIResponse);

    // If YouTube enrichment changed the response, send a patch event
    if (enrichedResponse !== fullAIResponse) {
      res.write(`data: ${JSON.stringify({ type: 'youtube_enrichment', content: enrichedResponse })}\n\n`);
      fullAIResponse = enrichedResponse;
    }

    res.write('data: [DONE]\n\n');
    res.end();

    // Cache the initial teaching response for this chunk/level
    if (!cachedResponse) await setCached(cacheKey, fullAIResponse, CACHE_TTL.TEACHING);

    // 2. Auto-save flashcards if this was a flashcard mode response
    if (session.mode === 'flashcards') {
      const flashcards = parseFlashcardsFromResponse(fullAIResponse);
      if (flashcards.length > 0) {
        const flashcardDocs = flashcards.map(fc => ({
          ...fc,
          documentId: document._id,
          documentTitle: document.title || 'Untitled Document',
          savedAt: new Date(),
        }));

        // Atomic push — append to existing savedFlashcards array
        await StudentProfile.findOneAndUpdate(
          { userId },
          { $push: { savedFlashcards: { $each: flashcardDocs } } }
        );

        // Bust profile cache so the new flashcards are visible immediately
        await deleteCached(CACHE_KEYS.PROFILE(userId));

        // Notify client that flashcards were saved
        // (res is already ended, so this data is sent before DONE in the next request)
        // We embed this as metadata in the conversation record for the frontend to read
      }
    }

    conversation.messages.push(
      { role: 'user', content: message },
      { role: 'assistant', content: fullAIResponse }
    );
    await conversation.save();
  } catch (error) {
    if (!res.writableEnded) {
      res.write(`data: ${JSON.stringify({ error: 'AI Stream interrupted' })}\n\n`);
      res.end();
    }
  } finally {
    await deleteCached(streamLockKey);
  }
});

export const getSession = asyncHandler(async (req, res) => {
  const session = await Session.findOne({ _id: req.params.id, userId: req.user.id })
    .populate('documentId', 'title subject');
  
  if (!session) throw new AppError('Session not found', 404);
  if (session.userId.toString() !== req.user.id) throw new AppError('Forbidden: Access denied', 403);
  
  const conversation = await Conversation.findOne({ sessionId: session._id });

  res.status(200).json({ session, messages: conversation?.messages || [] });
});

export const completeSession = asyncHandler(async (req, res) => {
  const session = await Session.findOneAndUpdate(
    { _id: req.params.id, userId: req.user.id },
    { status: 'completed', completedAt: new Date() },
    { new: true }
  );

  if (!session) throw new AppError('Session not found', 404);

  // Respond immediately to the client
  res.status(200).json({ 
    status: 'success', 
    message: "Awesome job on completing this session! I'm updating your profile strengths and weaknesses now." 
  });

  // Trigger background analysis via service (non-blocking)
  AdaptationService.extractSessionInsights(session._id);
});

/**
 * Allows the student to switch modes, move to next chunk, or set preparation style.
 */
export const updateSessionState = asyncHandler(async (req, res) => {
  const { id: sessionId } = req.params;
  const { mode, currentChunkIndex, mentorSuggestion, preparationStyle } = req.body;
  const userId = req.user.id;

  const session = await Session.findOne({ _id: sessionId, userId });
  if (!session || (session.status !== 'active' && session.status !== 'completed')) {
    throw new AppError('Session not found or inactive', 404);
  }

  // Auto-reactivate completed sessions when updating their state
  if (session.status === 'completed') {
    await Session.updateMany(
      { userId, documentId: session.documentId, status: 'active', _id: { $ne: session._id } },
      { status: 'abandoned' }
    );
    session.status = 'active';
    session.completedAt = undefined;
  }

  if (mode) session.mode = mode;
  if (typeof currentChunkIndex === 'number') session.currentChunkIndex = currentChunkIndex;
  if (mentorSuggestion) session.mentorSuggestions.push(mentorSuggestion);
  // Allow frontend to explicitly set preparation style (dual mechanism with AI asking in chat)
  if (preparationStyle) session.preparationStyle = preparationStyle;

  await session.save();

  res.status(200).json({ status: 'success', session });
});

/**
 * Returns the student's saved flashcards, grouped by document then topic.
 * Accessed via GET /api/sessions/flashcards (not session-specific — shows all saved cards).
 */
export const getMyFlashcards = asyncHandler(async (req, res) => {
  const userId = req.user.id;

  const profile = await StudentProfile.findOne({ userId })
    .select('savedFlashcards')
    .populate('savedFlashcards.documentId', 'title subject');

  if (!profile) throw new AppError('Profile not found', 404);

  // Group by documentId → topic for organised library view
  const grouped = {};
  for (const card of (profile.savedFlashcards || [])) {
    const docId = card.documentId?._id?.toString() || card.documentId?.toString();
    const docTitle = card.documentTitle || card.documentId?.title || 'Untitled';

    if (!grouped[docId]) {
      grouped[docId] = { documentId: docId, documentTitle: docTitle, topics: {} };
    }

    const topic = card.topic || 'General';
    if (!grouped[docId].topics[topic]) {
      grouped[docId].topics[topic] = [];
    }

    grouped[docId].topics[topic].push({
      front: card.front,
      back:  card.back,
      savedAt: card.savedAt,
    });
  }

  // Convert to array for easy frontend consumption
  const library = Object.values(grouped).map(doc => ({
    documentId: doc.documentId,
    documentTitle: doc.documentTitle,
    topics: Object.entries(doc.topics).map(([topic, cards]) => ({ topic, cards })),
  }));

  res.status(200).json({ status: 'success', total: profile.savedFlashcards?.length || 0, library });
});

/**
 * Returns a personalised AI tutor welcome for a freshly opened session.
 * Uses topics + summary extracted by the background worker.
 */
export const getWelcomeMessage = asyncHandler(async (req, res) => {
  const { id: sessionId } = req.params;
  const userId = req.user.id;

  const session = await Session.findOne({ _id: sessionId, userId });
  if (!session) throw new AppError('Session not found', 404);

  const document = await Document.findById(session.documentId)
    .select('title topics summary totalChunks');
  if (!document) throw new AppError('Document not found', 404);

  const profile = await ProfileService.getProfile(userId);
  if (!profile) throw new AppError('Student profile not found', 404);

  const name = req.user.name === 'New Student' ? '' : req.user.name;
  const firstName = name?.split(' ')[0] || 'there';

  const topics = document.topics || [];
  const summary = document.summary || '';
  const weakTopics = profile.weakTopics || [];
  const strongTopics = profile.strongTopics || [];
  const totalChunks = document.totalChunks || 1;

  // ── Richer, personalised welcome ──────────────────────────────────────────
  let welcomeText = `Hey ${firstName}! 👋 I've finished reading your **${document.title}** notes and I'm ready to teach you.`;

  if (totalChunks > 1) {
    welcomeText += `\n\nThis document has **${totalChunks} sections** — we'll work through them together at your pace.`;
  }

  if (summary) {
    welcomeText += `\n\n📖 **What this is about:**\n${summary}`;
  }

  if (topics.length > 0) {
    welcomeText += `\n\n🗂️ **${topics.length} key topic${topics.length > 1 ? 's' : ''} I found:**`;
    topics.forEach((t, i) => {
      welcomeText += `\n${i + 1}. ${t}`;
    });
  }

  // Personalise based on profile history
  const relevantWeakTopics = weakTopics.filter(w =>
    topics.some(t => t.toLowerCase().includes(w.toLowerCase()) || w.toLowerCase().includes(t.toLowerCase()))
  );

  if (relevantWeakTopics.length > 0) {
    welcomeText += `\n\n⚠️ **Heads up:** Based on your past sessions, you've found **${relevantWeakTopics.join(', ')}** tricky before. I'll make sure we give those extra attention today.`;
  }

  if (strongTopics.length > 0) {
    const relevantStrong = strongTopics.filter(s =>
      topics.some(t => t.toLowerCase().includes(s.toLowerCase()) || s.toLowerCase().includes(t.toLowerCase()))
    );
    if (relevantStrong.length > 0) {
      welcomeText += `\n\n✅ You've already shown strong understanding of **${relevantStrong.join(', ')}** — we'll build on that.`;
    }
  }

  welcomeText += `\n\n**How would you like to start?**`;

  const learningModes = [
    { id: 'understand', label: '📚 Understand',    description: 'I explain each section step-by-step with examples. Best for first-time learning.' },
    { id: 'review',     label: '🔄 Review',        description: 'Quick recap of key points. Best when you already know the material.' },
    { id: 'practice',   label: '✏️ Practice',      description: 'I quiz you inline, one question at a time, with instant feedback.' },
    { id: 'prepare',    label: '🎯 Prepare',       description: 'Exam simulation. I\'ll ask your preferred style — story, MCQ, theory, or mixed.' },
    { id: 'ask',        label: '💬 Ask Anything',  description: 'Free-form chat. Ask me anything about the document.' },
    { id: 'flashcards', label: '🃏 Flashcards',    description: 'I generate flashcards and save them to your profile for later review.' },
  ];

  res.status(200).json({
    status: 'success',
    welcome: {
      message: welcomeText,
      topics,
      summary,
      documentTitle: document.title,
      totalChunks,
      learningModes,
    },
  });
});